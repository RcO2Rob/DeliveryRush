#!/usr/bin/env python3
"""Generate shared C++ collision geometry from the city author's JSON layout."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def generate():
    data = json.loads((ROOT / 'Design/city_layout.json').read_text())
    def rows(boxes):
        return ',\n'.join('    {' + ', '.join(str(b[k]) for k in ('x','y','hx','hy','height')) + '}' for b in boxes)
    solids = data['buildings'] + data.get('obstacles', [])
    nodes = ',\n'.join('    {%s, %s}' % tuple(p) for p in data['navigation_nodes'])
    segments = [(a[0],a[1],b[0],b[1],path['width']) for path in data['park_paths']
                for a,b in zip(path['points'],path['points'][1:])]
    path_rows = ',\n'.join('    {' + ', '.join(map(str,segment)) + '}' for segment in segments)
    hills = data['terrain']['hills']
    hill_rows = ',\n'.join('    {' + ', '.join(str(h[k]) for k in ('x','y','rx','ry','height')) + '}' for h in hills)
    text = '''#pragma once
// Generated by tools/generate_city_layout.py. Edit Design/city_layout.json.
#include <array>
namespace Delivery {
struct Building { double x, y, hx, hy, height; double yaw=0; };
inline constexpr std::array<Building, %d> CityBuildings{{
%s
}};
inline constexpr std::array<Building, %d> ParkObstacles{{
%s
}};
inline constexpr std::array<Building, %d> CityObstacles{{
%s
}};
struct NavigationNode { double x, y; };
inline constexpr std::array<NavigationNode, %d> NavigationNodes{{
%s
}};
inline constexpr double ParkMinX = %s;
struct PathSegment { double ax, ay, bx, by, width; };
inline constexpr std::array<PathSegment, %d> ParkPathSegments{{
%s
}};
struct TerrainHill { double x, y, rx, ry, height; };
inline constexpr std::array<TerrainHill, %d> TerrainHills{{
%s
}};
inline constexpr double TerrainGridStep = %s, TerrainExtent = %s;
inline constexpr double WorldLimit = %s;
inline constexpr double StartX = %s, StartY = %s;
inline constexpr double DestinationX = %s, DestinationY = %s;
inline constexpr double DeliveryTime = %s;
}
''' % (len(data['buildings']), rows(data['buildings']), len(data['obstacles']), rows(data['obstacles']),
       len(solids), rows(solids), len(data['navigation_nodes']), nodes, data['park_min_x'], len(segments), path_rows,
       len(hills),hill_rows,data['terrain']['grid_step'],data['terrain']['extent'],
       data['world_limit'], *data['start'], *data['destination'], data['time_limit'])
    output = ROOT / 'Source/DeliveryRush/CityLayoutData.h'
    if not output.exists() or output.read_text() != text:
        output.write_text(text)
    return data

if __name__ == '__main__':
    generate()
